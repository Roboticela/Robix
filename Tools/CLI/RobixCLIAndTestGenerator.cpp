std::string TestScaffoldGenerator::ComputeCompanionTestPath(std::string_view sourceFilePath) {
    std::string pathStr(sourceFilePath);
    if (StdLib::StringOps::EndsWith(pathStr, ".test.rx")) {
        return pathStr;
    }
    if (StdLib::StringOps::EndsWith(pathStr, ".rx")) {
        return pathStr.substr(0, pathStr.size() - 4) + ".test.rx";
    }
    return pathStr + ".test.rx";
}

std::string TestScaffoldGenerator::SynthesizeTestFileContent(
    std::string_view sourceFilePath,
    std::string_view sourceCode) {

    Frontend::DiagnosticBag diags;
    Frontend::Lexer lexer(sourceCode, sourceFilePath, diags);
    Frontend::Parser parser(lexer.TokenizeAll(), sourceFilePath, diags);
    const auto ast = parser.ParseCompilationUnit();

    // Extract stem name (e.g., "Source/MotorController.rx" -> "MotorController")
    std::filesystem::path fsPath{ std::string(sourceFilePath) };
    std::string stemName = fsPath.stem().string();
    if (stemName.empty()) {
        stemName = "Module";
    }

    std::ostringstream out;
    if (!ast.packageName.empty()) {
        out << "package " << ast.packageName << ";\n\n";
    } else {
        out << "package Tests;\n\n";
    }

    out << "import Robix.Testing;\n\n";

    std::size_t generatedTestBlocks = 0;
    for (const auto& declPtr : ast.declarations) {
        if (!declPtr) continue;

        if (declPtr->kind == Frontend::DeclKind::Function) {
            out << "Test \"" << stemName << "." << declPtr->name << "\" {\n";
            out << "    // Empty test scaffold generated by Robix CLI for " << declPtr->name << "\n";
            out << "}\n\n";
            ++generatedTestBlocks;
        } else if (declPtr->kind == Frontend::DeclKind::Class) {
            out << "Test \"" << declPtr->name << " Construction\" {\n";
            out << "    // Empty test scaffold generated by Robix CLI for class " << declPtr->name << "\n";
            out << "}\n\n";
            ++generatedTestBlocks;

            for (const auto& memberPtr : declPtr->members) {
                if (!memberPtr) continue;
                if (memberPtr->kind == Frontend::DeclKind::Function) {
                    out << "Test \"" << declPtr->name << "." << memberPtr->name << "\" {\n";
                    out << "    // Empty test scaffold generated by Robix CLI for method " << declPtr->name << "." << memberPtr->name << "\n";
                    out << "}\n\n";
                    ++generatedTestBlocks;
                }
            }
        }
    }

    if (generatedTestBlocks == 0) {
        out << "Test \"" << stemName << " Default\" {\n";
        out << "    // Empty test scaffold generated by Robix CLI\n";
        out << "}\n";
    }

    return out.str();
}

bool TestScaffoldGenerator::EnsureTestFileForSourceOnDisk(
    const std::filesystem::path& rxFilePath,
    TestScaffoldReport& reportOut) {

    const std::string pathStr = rxFilePath.generic_string();
    if (!StdLib::StringOps::EndsWith(pathStr, ".rx") ||
        StdLib::StringOps::EndsWith(pathStr, ".test.rx")) {
        return false;
    }

    const std::filesystem::path companionPath{ ComputeCompanionTestPath(pathStr) };

    // Also check if `<ParentOfSource>/Tests/<Stem>.test.rx` exists
    std::filesystem::path projectTestsCandidate;
    if (rxFilePath.has_parent_path() && rxFilePath.parent_path().filename() == "Source") {
        projectTestsCandidate = rxFilePath.parent_path().parent_path() / "Tests" / (rxFilePath.stem().string() + ".test.rx");
    }

    if (std::filesystem::exists(companionPath)) {
        reportOut.skippedExistingTestFiles.push_back(companionPath.generic_string());
        return false;
    }
    if (!projectTestsCandidate.empty() && std::filesystem::exists(projectTestsCandidate)) {
        reportOut.skippedExistingTestFiles.push_back(projectTestsCandidate.generic_string());
        return false;
    }

    std::string sourceCode;
    {
        std::ifstream inFile(rxFilePath, std::ios::in | std::ios::binary);
        if (inFile) {
            std::ostringstream buffer;
            buffer << inFile.rdbuf();
            sourceCode = buffer.str();
        }
    }

    const std::string testContent = SynthesizeTestFileContent(pathStr, sourceCode);
    std::filesystem::path outputPath = companionPath;
    if (!projectTestsCandidate.empty() &&
        std::filesystem::exists(projectTestsCandidate.parent_path())) {
        outputPath = projectTestsCandidate;
    }

    if (outputPath.has_parent_path()) {
        std::filesystem::create_directories(outputPath.parent_path());
    }

    std::ofstream outFile(outputPath, std::ios::out | std::ios::binary | std::ios::trunc);
    if (!outFile) {
        return false;
    }
    outFile << testContent;
    outFile.close();

    reportOut.createdTestFiles.push_back(outputPath.generic_string());
    return true;
}

TestScaffoldReport TestScaffoldGenerator::GenerateMissingTestFilesOnDisk(
    const std::filesystem::path& targetPath) {

    TestScaffoldReport report;
    if (!std::filesystem::exists(targetPath)) {
        return report;
    }

    if (std::filesystem::is_regular_file(targetPath)) {
        EnsureTestFileForSourceOnDisk(targetPath, report);
        return report;
    }

    for (const auto& entry : std::filesystem::recursive_directory_iterator(targetPath)) {
        if (!entry.is_regular_file()) continue;
        const std::string p = entry.path().generic_string();
        if (StdLib::StringOps::EndsWith(p, ".rx") &&
            !StdLib::StringOps::EndsWith(p, ".test.rx")) {
            EnsureTestFileForSourceOnDisk(entry.path(), report);
        }
    }
    return report;
}

TestScaffoldReport TestScaffoldGenerator::GenerateMissingTestFilesInMemory(
    std::map<std::string, std::string>& projectFiles) {

    TestScaffoldReport report;
    std::vector<std::pair<std::string, std::string>> sourcesToInspect;
    for (const auto& [path, content] : projectFiles) {
        if (StdLib::StringOps::EndsWith(path, ".rx") &&
            !StdLib::StringOps::EndsWith(path, ".test.rx")) {
            sourcesToInspect.emplace_back(path, content);
        }
    }

    for (const auto& [srcPath, srcContent] : sourcesToInspect) {
        const std::string companionPath = ComputeCompanionTestPath(srcPath);
        std::filesystem::path fsSrc{ srcPath };
        const std::string stemTestName = "Tests/" + fsSrc.stem().string() + ".test.rx";

        if (projectFiles.count(companionPath) > 0) {
            report.skippedExistingTestFiles.push_back(companionPath);
            continue;
        }
        if (projectFiles.count(stemTestName) > 0) {
            report.skippedExistingTestFiles.push_back(stemTestName);
            continue;
        }

        const std::string testContent = SynthesizeTestFileContent(srcPath, srcContent);
        projectFiles[companionPath]   = testContent;
        report.createdTestFiles.push_back(companionPath);
    }

    return report;
}

