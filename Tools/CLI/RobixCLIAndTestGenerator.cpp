CLICommandResult RobixCLIDispatcher::ExecuteCommand(
    CLIBinaryKind binaryKind,
    const std::vector<std::string>& args,
    std::map<std::string, std::string>* optionalInMemoryFiles) {

    CLICommandResult result;
    if (args.empty()) {
        result.exitCode   = 1;
        result.stderrText = "Usage: robix <command> [options] | robixc <file.rx> [options]\n";
        return result;
    }

    const std::string& cmd = args[0];

    // ------------------------------------------------------------------------
    // 1. Test Scaffold Generation Commands:
    //    - `robix test-gen [Path]` / `robix generate-tests [Path]`
    //    - `robix test --generate [Path]`
    //    - `robixc --generate-tests [Path]`
    // ------------------------------------------------------------------------
    const bool isTestGenCommand =
        (cmd == "test-gen" || cmd == "generate-tests" ||
         (cmd == "test" && (HasFlag(args, "--generate") || HasFlag(args, "--init"))) ||
         HasFlag(args, "--generate-tests"));

    if (isTestGenCommand) {
        if (optionalInMemoryFiles) {
            result.generatedTests = TestScaffoldGenerator::GenerateMissingTestFilesInMemory(*optionalInMemoryFiles);
        } else {
            std::string targetPath = ".";
            for (std::size_t i = 1; i < args.size(); ++i) {
                if (!StdLib::StringOps::StartsWith(args[i], "--")) {
                    targetPath = args[i];
                    break;
                }
            }
            result.generatedTests = TestScaffoldGenerator::GenerateMissingTestFilesOnDisk(targetPath);
        }

        std::ostringstream msg;
        msg << "Test Scaffold Generator: created " << result.generatedTests.createdTestFiles.size()
            << " missing .test.rx file(s), skipped " << result.generatedTests.skippedExistingTestFiles.size()
            << " existing .test.rx file(s).\n";
        result.stdoutText = msg.str();
        result.exitCode   = 0;

        // If command was purely `test-gen` / `generate-tests` / `--generate-tests`, return immediately
        if (cmd == "test-gen" || cmd == "generate-tests" || HasFlag(args, "--generate-tests")) {
            return result;
        }
    }

    // ------------------------------------------------------------------------
    // 2. Direct Native Compiler (`robixc`)
    // ------------------------------------------------------------------------
    if (binaryKind == CLIBinaryKind::RobixNativeCompiler) {
        if (cmd == "run" && args.size() >= 2) {
            auto srcOpt = LoadSourceFile(args[1], optionalInMemoryFiles);
            if (!srcOpt) {
                result.exitCode   = 1;
                result.stderrText = "robixc run: file not found: " + args[1];
                return result;
            }
            return RunSingleSourceFile(args[1], *srcOpt, false, false);
        }
        if (cmd == "test" && args.size() >= 2) {
            if (optionalInMemoryFiles) {
                result.generatedTests = TestScaffoldGenerator::GenerateMissingTestFilesInMemory(*optionalInMemoryFiles);
            }
            auto srcOpt = LoadSourceFile(args[1], optionalInMemoryFiles);
            if (!srcOpt) {
                result.exitCode   = 1;
                result.stderrText = "robixc test: file not found: " + args[1];
                return result;
            }
            return RunSingleSourceFile(args[1], *srcOpt, true, false);
        }
        // Single-file native compile (`robixc Main.rx`)
        auto srcOpt = LoadSourceFile(cmd, optionalInMemoryFiles);
        if (!srcOpt) {
            result.exitCode   = 1;
            result.stderrText = "robixc: file not found: " + cmd;
            return result;
        }
        return RunSingleSourceFile(cmd, *srcOpt, false, true);
    }

    // ------------------------------------------------------------------------
    // 3. Unified CLI (`robix`)
    // ------------------------------------------------------------------------
    if (cmd == "run") {
        std::string targetFile = (args.size() >= 2 && !StdLib::StringOps::StartsWith(args[1], "--"))
                                     ? args[1]
                                     : "Source/Main.rx";
        auto srcOpt = LoadSourceFile(targetFile, optionalInMemoryFiles);
        if (!srcOpt) {
            result.exitCode   = 1;
            result.stderrText = "robix run: file not found: " + targetFile;
            return result;
        }
        return RunSingleSourceFile(targetFile, *srcOpt, false, false);
    }

    if (cmd == "test") {
        // Automatically generate missing `.test.rx` files with empty tests if `--generate` or `--auto-scaffold` is passed
        if (HasFlag(args, "--generate") || HasFlag(args, "--auto-scaffold")) {
            if (optionalInMemoryFiles) {
                result.generatedTests = TestScaffoldGenerator::GenerateMissingTestFilesInMemory(*optionalInMemoryFiles);
            }
        }
        std::string targetFile = "Tests/Main.test.rx";
        for (std::size_t i = 1; i < args.size(); ++i) {
            if (!StdLib::StringOps::StartsWith(args[i], "--")) {
                targetFile = args[i];
                break;
            }
        }
        std::optional<std::string> srcOpt;
        if (StdLib::StringOps::EndsWith(targetFile, ".test.rx")) {
            srcOpt = LoadSourceFile(targetFile, optionalInMemoryFiles);
        } else {
            const std::string companion = TestScaffoldGenerator::ComputeCompanionTestPath(targetFile);
            srcOpt = LoadSourceFile(companion, optionalInMemoryFiles);
            if (srcOpt) {
                targetFile = companion;
            } else {
                srcOpt = LoadSourceFile(targetFile, optionalInMemoryFiles);
            }
        }
        if (!srcOpt) {
            result.exitCode   = 1;
            result.stderrText = "robix test: test file not found: " + targetFile;
            return result;
        }
        auto runRes           = RunSingleSourceFile(targetFile, *srcOpt, true, false);
        runRes.generatedTests = std::move(result.generatedTests);
        return runRes;
    }

    if (cmd == "verify" || cmd == "check") {
        if (args.size() >= 2) {
            auto srcOpt = LoadSourceFile(args[1], optionalInMemoryFiles);
            if (!srcOpt) {
                result.exitCode   = 1;
                result.stderrText = "robix verify: file not found: " + args[1];
                return result;
            }
            auto rep          = RobixVerifier::VerifySingleFile(args[1], *srcOpt);
            result.exitCode   = rep.exitCode;
            result.stdoutText = rep.FormatSummary();
            return result;
        }
    }

    if (cmd == "interpreter") {
        result.exitCode   = 0;
        result.stdoutText = "Robix Bytecode Virtual Machine v1.0.0 (Dual Engine Architecture)\n";
        return result;
    }

    result.exitCode   = 0;
    result.stdoutText = "Robix CLI executed command: " + cmd + "\n";
    return result;
}

CLICommandResult RobixCLIDispatcher::EvaluateReplLine(std::string_view replInputLine) {
    std::ostringstream wrapped;
    wrapped << "package Repl;\n"
            << "public Function Main() -> Void {\n"
            << "    " << replInputLine << "\n"
            << "}\n";
    return RunSingleSourceFile("Repl.rx", wrapped.str(), false, false);
}

