std::optional<std::string> LoadSourceFile(
    const std::string& path,
    const std::map<std::string, std::string>* inMemoryFiles) {

    if (inMemoryFiles) {
        auto it = inMemoryFiles->find(path);
        if (it != inMemoryFiles->end()) {
            return it->second;
        }
    }
    if (std::filesystem::exists(path)) {
        std::ifstream in(path, std::ios::in | std::ios::binary);
        if (in) {
            std::ostringstream ss;
            ss << in.rdbuf();
            return ss.str();
        }
    }
    return std::nullopt;
}

bool HasFlag(const std::vector<std::string>& args, std::string_view flag) {
    for (const auto& a : args) {
        if (a == flag) return true;
    }
    return false;
}

CLICommandResult RunSingleSourceFile(
    const std::string& fileName,
    const std::string& sourceCode,
    bool executeTests,
    bool emitNativeLLVMIR) {

    CLICommandResult res;
    Frontend::DiagnosticBag diags;
    Frontend::Lexer lexer(sourceCode, fileName, diags);
    Frontend::Parser parser(lexer.TokenizeAll(), fileName, diags);
    auto ast = parser.ParseCompilationUnit();
    Frontend::ResolveImports(ast, fileName, diags);

    Frontend::TypeCheckerOptions tcOpts;
    tcOpts.strictStyleMode = false;
    tcOpts.requireExplain  = false;
    Frontend::TypeChecker tc(diags, tcOpts);
    tc.CheckCompilationUnit(ast);

    Frontend::SemanticAnalyzer sem(diags);
    sem.AnalyzeCompilationUnit(ast);

    if (diags.HasErrors()) {
        res.exitCode   = 1;
        res.stderrText = diags.FormatHumanReadable();
        return res;
    }

    IR::SSAIRBuilder irBuilder(sem, diags);
    auto irMod = irBuilder.LowerCompilationUnit(ast);

    if (!executeTests) {
        IR::IRPassManager passMgr(sem, diags);
        passMgr.RunOptimizationPipeline(irMod, true);
    }

    if (emitNativeLLVMIR) {
        CodeGen::LLVMIRGenerator llvmGen(diags);
        res.stdoutText = llvmGen.GenerateLLVMIR(irMod);
        res.exitCode   = diags.HasErrors() ? 1 : 0;
        return res;
    }

    VM::BytecodeGenerator bcGen(diags);
    auto bcMod = bcGen.GenerateFromIR(irMod);
    VM::BytecodeVM vm(bcMod);

    if (executeTests) {
        auto suiteRes  = vm.ExecuteAllTests();
        res.stdoutText = vm.GetStdoutBuffer() +
                         "Executed test blocks: " + std::to_string(suiteRes.passedTests) +
                         " passed, " + std::to_string(suiteRes.failedTests) + " failed.\n";
        for (const auto& message : suiteRes.failureMessages) {
            res.stdoutText += message + "\n";
        }
        res.exitCode   = (suiteRes.failedTests == 0) ? 0 : 1;
    } else {
        res.exitCode   = vm.ExecuteMainAndGetExitCode();
        res.stdoutText = vm.GetStdoutBuffer();
    }
    return res;
}

